import { act, renderHook, waitFor } from "@testing-library/react";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { afterEach, expect, it, vi } from "vitest";
import type { ReactNode } from "react";
import { useAccessMutation } from "./use-access-mutation";
const { centralFetch } = vi.hoisted(() => ({ centralFetch: vi.fn() }));
vi.mock("@/api/client", async () => ({ ...await vi.importActual<typeof import("@/api/client")>("@/api/client"), centralFetch }));
afterEach(() => centralFetch.mockReset());
it("keeps a server-acknowledged change confirmed when its list refresh fails", async () => {
  centralFetch.mockResolvedValue(undefined);
  const refresh = vi.fn().mockRejectedValueOnce(new Error("read failed")).mockResolvedValue(undefined);
  const client = new QueryClient();
  const wrapper = ({ children }: { children: ReactNode }) => <QueryClientProvider client={client}>{children}</QueryClientProvider>;
  const hook = renderHook(() => useAccessMutation("actor:session:project", refresh, vi.fn()), { wrapper });
  let confirmed = false;
  await act(async () => { confirmed = await hook.result.current.submit({ path: "/projects/p/memberships/u", method: "DELETE" }, "Project access was removed."); });
  expect(confirmed).toBe(true);
  expect(hook.result.current.uncertain).toBe(false);
  expect(hook.result.current.error).toBe("");
  expect(hook.result.current.success).toBe("Project access was removed.");
  expect(centralFetch).toHaveBeenCalledTimes(1);
  await act(async () => { await hook.result.current.retry("Must not resend."); });
  expect(centralFetch).toHaveBeenCalledTimes(1);
  expect(hook.result.current.refreshFailed).toBe(true);
  await act(async () => { await hook.result.current.reload(); });
  expect(hook.result.current.refreshFailed).toBe(false);
  expect(centralFetch).toHaveBeenCalledTimes(1);
  await waitFor(() => expect(hook.result.current.busy).toBe(false));
});
